// PURE: builds the private wrangler.jsonc content. Never receives or emits secret values.
export const DEFAULT_CRON = "30 12 * * *"; // 6 PM IST
export const COMPATIBILITY_DATE = "2026-09-24";

export function environmentFor(envName) {
  return envName === "production" ? "production" : "development";
}

export function effectiveCron(answers) {
  if (answers.features.email) return answers.email.cron;
  if (answers.features.retention) return DEFAULT_CRON; // retention runs inside the scheduled handler
  return null;
}

export function buildEnvBlock(answers, ids) {
  const vars = {
    ENVIRONMENT: environmentFor(answers.env),
    MAX_RECORDING_BYTES: String(answers.maxRecordingMb * 1024 * 1024),
    CALL_SUMMARY_ENABLED: answers.features.email ? "true" : "false",
  };
  if (answers.features.retention) vars.RECORDING_RETENTION_DAYS = String(answers.retention.days);
  if (answers.features.access && ids.accessIssuer && ids.accessAudience) {
    vars.ACCESS_TEAM_DOMAIN = ids.accessIssuer;
    vars.ACCESS_AUDIENCE = ids.accessAudience;
  }
  const cron = effectiveCron(answers);
  return {
    name: answers.workerName,
    workers_dev: true,
    preview_urls: false,
    ...(cron ? { triggers: { crons: [cron] } } : {}),
    vars,
    d1_databases: [
      { binding: "DB", database_name: answers.d1Name, database_id: ids.d1Id, migrations_dir: "migrations" },
    ],
    r2_buckets: [{ binding: "RECORDINGS", bucket_name: answers.r2Name }],
  };
}

/**
 * Full config object. Top-level bindings stay local-only placeholders so `npm run dev` keeps working;
 * remote commands always select the named env. `existingEnvs` preserves other environments of a previous file.
 */
export function buildWranglerConfig(answers, ids, existingEnvs = {}) {
  return {
    $schema: "./node_modules/wrangler/config-schema.json",
    name: "linekeep-api",
    main: "src/index.ts",
    account_id: ids.accountId,
    preview_urls: false,
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat"],
    observability: {
      enabled: true,
      redact_query_string: true,
      logs: { enabled: true, invocation_logs: false },
    },
    vars: { ENVIRONMENT: "development", MAX_RECORDING_BYTES: "104857600" },
    d1_databases: [
      {
        binding: "DB",
        database_name: "linekeep-local",
        database_id: "00000000-0000-0000-0000-000000000000",
        migrations_dir: "migrations",
      },
    ],
    r2_buckets: [{ binding: "RECORDINGS", bucket_name: "linekeep-recordings-local" }],
    env: { ...existingEnvs, [answers.env]: buildEnvBlock(answers, ids) },
  };
}

export function renderWranglerConfig(config) {
  return [
    "// Generated by `npm run setup`. Private (git-ignored): contains resource IDs but no secrets.",
    "// Top-level bindings are local only. Always select --env for remote commands.",
    JSON.stringify(config, null, 2),
    "",
  ].join("\n");
}

/** Strip // and /* *\/ comments and trailing commas (outside strings), then JSON.parse. Throws on invalid input. */
export function parseJsonc(source) {
  let out = "";
  let i = 0;
  const n = source.length;
  while (i < n) {
    const c = source[i];
    if (c === '"') {
      let j = i + 1;
      while (j < n && source[j] !== '"') j += source[j] === "\\" ? 2 : 1;
      out += source.slice(i, j + 1);
      i = j + 1;
    } else if (c === "/" && source[i + 1] === "/") {
      while (i < n && source[i] !== "\n") i++;
    } else if (c === "/" && source[i + 1] === "*") {
      const end = source.indexOf("*/", i + 2);
      i = end === -1 ? n : end + 2;
    } else {
      out += c;
      i++;
    }
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

export function backupName(now = new Date()) {
  return `wrangler.jsonc.${now.toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z")}.bak`;
}
